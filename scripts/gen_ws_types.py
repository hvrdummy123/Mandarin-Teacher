#!/usr/bin/env python3
"""Emit a small TypeScript types file from ws_schema message names."""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "frontend" / "src" / "lib" / "wsTypes.ts"

CONTENT = '''/* Generated by scripts/gen_ws_types.py — edit ws_schema.py then re-run. */
export type WsClientMessage =
  | { type: "session.start"; session_id: number; level?: number }
  | { type: "turn.start" }
  | { type: "turn.end" };

export type WsServerMessage =
  | { type: "transcript.user"; message: Record<string, unknown> }
  | { type: "reply.delta"; text: string }
  | { type: "reply.sentence"; text: string; message?: Record<string, unknown> }
  | { type: "analysis"; analysis: Record<string, unknown> }
  | { type: "tone.report"; report: Record<string, unknown> }
  | { type: "xp.awarded"; points: number }
  | { type: "turn.end" }
  | { type: "error"; detail: string };
'''


def main() -> None:
    OUT.write_text(CONTENT, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
